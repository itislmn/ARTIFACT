os.environ.setdefault("OPENBLAS_NUM_THREADS", "1")
os.environ.setdefault("OMP_NUM_THREADS", "1")

import argparse  # noqa: E402
import json  # noqa: E402
import multiprocessing as mp  # noqa: E402
import queue  # noqa: E402
import socket  # noqa: E402
import threading  # noqa: E402
import time  # noqa: E402
from collections import deque  # noqa: E402
from pathlib import Path  # noqa: E402

import numpy as np  # noqa: E402

from backend.settings import ROOT, load_config, radar_dir  # noqa: E402

LIVE_CFG = ROOT / "radar_live.cfg"


def live_cfg(cfg: dict) -> Path:
    src = (ROOT / cfg["radar"]["cfg"]).resolve()
    lines = []
    for line in src.read_text(encoding="utf-8", errors="ignore").splitlines():
        if line.strip().startswith("frameCfg"):
            v = line.split()
            v[4] = "0"
            line = " ".join(v)
        lines.append(line)
    LIVE_CFG.write_text(f"% generated by backend/radar_live.py from {src.name}: frameCfg numFrames 0 = continuous\n"
                        + "\n".join(lines) + "\n", encoding="utf-8")
    return LIVE_CFG


class _Receiver(threading.Thread):

    def __init__(self, cap, frame_bytes: int, raw_path: Path | None):
        super().__init__(daemon=True)
        self.sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        self.sock.setsockopt(socket.SOL_SOCKET, socket.SO_RCVBUF, 16 * 1024 * 1024)
        self.sock.settimeout(0.5)
        self.sock.bind((cap.PC_IP, cap.DATA_PORT))
        self.asm, self.header = cap.FrameAssembler(frame_bytes), cap.HEADER_BYTES
        self.raw = open(raw_path, "wb") if raw_path else None
        self.stop_evt, self.cond = threading.Event(), threading.Condition()
        self.frames = self.packets = self.lost = 0
        self.times, self.newest, self._last_seq = [], None, None

    def run(self):
        pkt = bytearray(2048)
        view = memoryview(pkt)
        while not self.stop_evt.is_set():
            try:
                n = self.sock.recv_into(pkt)
            except socket.timeout:
                continue
            except OSError:
                break
            if n <= self.header:
                continue
            self.packets += 1
            seq = int.from_bytes(pkt[0:4], "little")
            if self._last_seq is not None and seq > self._last_seq + 1:
                self.lost += seq - self._last_seq - 1
            self._last_seq = seq
            for frame in self.asm.push(int.from_bytes(pkt[4:10], "little"), view[self.header:n]):
                t = time.perf_counter()
                if self.raw:
                    self.raw.write(frame)
                with self.cond:
                    self.newest = (self.frames, t, bytes(frame))
                    self.times.append(t)
                    self.frames += 1
                    self.cond.notify_all()
        self.sock.close()
        if self.raw:
            self.raw.close()

    def take_newest(self, after: int, timeout: float):
        with self.cond:
            self.cond.wait_for(lambda: self.newest is not None and self.newest[0] > after, timeout)
            return self.newest if self.newest is not None and self.newest[0] > after else None


def _worker(cfg: dict, session: str, port: str, q, stop, log_path, raw_path):
    from backend.radar_link import RadarTakes, cluster

    def say(kind, **kw):
        q.put({"type": kind, **kw})

    rx = dca = cap = None
    try:
        rc = cfg["radar"]
        rt = RadarTakes(radar_dir(session), rc)
        import estimation.capture as cap
        from estimation.core.radar import RadarConfig, frame_from_words
        path = live_cfg(cfg)
        rcfg = RadarConfig.from_cfg(path)
        frame_bytes = rcfg.wire_bytes_per_frame(padded=True)
        n_s, k = rcfg.n_samples, rc["chirps"]
        tone = 2000 * np.cos(2 * np.pi * 40 * np.arange(n_s) / n_s)
        dummy = (tone[:, None, None] + np.random.default_rng(0).normal(0, 5, (n_s, k, rcfg.n_virt))).astype(np.float32)
        rt._process(dummy, rcfg, rt.array, [rt.method], rt.settings, [0], None, None)
        say("status", text=f"background {'yes' if rt.bg is not None else 'NO'}, calibration "
                           f"{'yes' if rt.cal is not None else 'NO'} (session {session}); arming on {port}")
        cap.sensor_stop(port)
        dca = cap.DCA1000()
        dca.start()
        rx = _Receiver(cap, frame_bytes, raw_path)
        rx.start()
        time.sleep(0.3)
        cap.send_cfg(port, path)
        say("armed", frame_period_s=rcfg.frame_period_s, frame_bytes=frame_bytes, cfg=str(path))
        log = open(log_path, "a", encoding="utf-8") if log_path else None
        window, last, processed, t_wait = deque(maxlen=rc["window_frames"]), -1, 0, time.perf_counter()
        while not stop.is_set():
            item = rx.take_newest(last, 0.5)
            if item is None:
                if time.perf_counter() - t_wait > 3.0:
                    say("error", text="no radar frame for 3 s (DCA1000 / Ethernet / cfg?)")
                    t_wait = time.perf_counter()
                continue
            idx, t, buf = item
            t_wait = time.perf_counter()
            frame = frame_from_words(np.frombuffer(buf, "<i2"), rcfg, True)
            t0 = time.perf_counter()
            res = rt._process(frame[:, :rc["chirps"]], rcfg, rt.array, [rt.method], rt.settings, [idx], rt.cal, rt.bg)
            dets = res.detections[rt.method.name]
            ms = 1e3 * (time.perf_counter() - t0)
            processed += 1
            window.append(dets)
            msg = {"type": "frame", "t": round(t, 6), "frame": idx, "dets": np.round(dets, 4).tolist(),
                   "objects": cluster(list(window), rt.tol_r, rt.tol_a, rc["min_rate"]), "ms": round(ms, 1),
                   "received": rx.frames, "processed": processed, "skipped": rx.frames - processed,
                   "packets": rx.packets, "lost": rx.lost, "incomplete": rx.asm.incomplete}
            q.put(msg)
            if log:
                log.write(json.dumps(msg) + "\n")
            last = idx
    except BaseException as e:                            # noqa: BLE001 - reported to the camera program
        say("error", text=f"{type(e).__name__}: {e}")
    finally:
        try:
            if cap is not None:
                cap.sensor_stop(port)
        except Exception:                                  # noqa: BLE001
            pass
        if rx is not None:
            rx.stop_evt.set()
            rx.join(timeout=2)
        if dca is not None:
            dca.stop()
        say("stopped", received=rx.frames if rx else 0, lost=rx.lost if rx else 0)


class LiveRadar:
    def __init__(self, cfg: dict, session: str, port: str | None = None, log_path: Path | None = None,
                 raw_path: Path | None = None):
        self.cfg, self.session = cfg, session
        self.port = port or cfg["radar"]["cli_port"]
        self.log_path, self.raw_path = log_path, raw_path
        self.last, self.armed, self.errors, self.status, self.frame_period_s = None, False, [], "starting", 0.1

    def start(self) -> "LiveRadar":
        ctx = mp.get_context("spawn")
        self.q, self.stop_evt = ctx.Queue(), ctx.Event()
        self.proc = ctx.Process(target=_worker, args=(self.cfg, self.session, self.port, self.q, self.stop_evt,
                                                      self.log_path, self.raw_path), daemon=True, name="radar")
        self.proc.start()
        return self

    def poll(self) -> list[dict]:
        msgs = []
        while True:
            try:
                m = self.q.get_nowait()
            except queue.Empty:
                break
            msgs.append(m)
            if m["type"] == "frame":
                self.last = m
            elif m["type"] == "armed":
                self.armed, self.status, self.frame_period_s = True, "armed", m["frame_period_s"]
            elif m["type"] == "error":
                self.errors.append(m["text"])
                self.status = "ERROR " + m["text"]
                print("  [radar] ERROR " + m["text"], flush=True)
            elif m["type"] == "status":
                self.status = m["text"]
                print("  [radar] " + m["text"], flush=True)
        return msgs

    def wait_armed(self, timeout: float = 60.0, tick=None):
        t0 = time.perf_counter()
        while not self.armed and time.perf_counter() - t0 < timeout:
            self.poll()
            if self.errors or not self.proc.is_alive():
                raise SystemExit("radar could not be armed: " + " | ".join(self.errors or ["process ended"]))
            if tick:
                tick()
            else:
                time.sleep(0.05)
        if not self.armed:
            raise SystemExit("radar not armed within %.0f s" % timeout)

    def stop(self):
        if hasattr(self, "stop_evt"):
            self.stop_evt.set()
            self.proc.join(timeout=10)
            self.poll()
            if self.proc.is_alive():
                self.proc.terminate()

    def __enter__(self):
        return self.start()

    def __exit__(self, *exc):
        self.stop()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--session", default=None)
    ap.add_argument("--cli", default=None, help="radar CLI port (default [radar] cli_port)")
    ap.add_argument("--seconds", type=float, default=15.0)
    args = ap.parse_args()
    cfg = load_config()
    session = args.session or cfg["session"]
    with LiveRadar(cfg, session, args.cli) as radar:
        radar.wait_armed()
        t0, shown = time.perf_counter(), -1
        while time.perf_counter() - t0 < args.seconds:
            radar.poll()
            m = radar.last
            if m and m["frame"] != shown and m["frame"] % 10 == 0:
                shown = m["frame"]
                print(f"frame {m['frame']:4d}: {m['received']} received, {m['skipped']} skipped, {m['lost']} packets lost, "
                      f"Infini-Rex {m['ms']:.0f} ms, objects " + "; ".join(f"{o['range_m']:.2f} m {o['azimuth_deg']:+.1f} deg"
                                                                for o in m["objects"]))
            time.sleep(0.05)
    m = radar.last
    if m:
        el = time.perf_counter() - t0
        print(f"\n{m['received']} frames in ~{el:.0f} s, {m['lost']} packets lost, {m['incomplete']} incomplete frames, "
              f"{m['skipped']} not processed (Infini-Rex slower than the frame rate)")


if __name__ == "__main__":
    main()
