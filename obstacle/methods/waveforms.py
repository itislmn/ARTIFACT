"""
waveforms.py - the chirp library and the advanced-frame configuration that preloads every chirp as a sub-frame
(tracking's waveform model).

    from methods.waveforms import Library
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field, replace
from pathlib import Path

import numpy as np

import paths
from methods.radar_config import C0, RadarConfig, with_layout

BASE_CFG = paths.WAVEFORMS / "base.cfg"
HANN_NOISE_BW = 1.5
BIN_FLOOR = 0.05


@dataclass(frozen=True)
class Waveform:
    name: str
    slope_mhz_us: float
    idle_us: float
    frame_ms: float
    subframe: int
    cfg: RadarConfig = field(repr=False)
    path: Path = field(repr=False)

    @property
    def range_res_m(self) -> float:
        return self.cfg.range_res_m

    @property
    def max_range_m(self) -> float:
        return 0.9 * self.cfg.fs_hz / 2 * C0 / (2 * self.cfg.slope_hz_per_s)

    @property
    def loop_s(self) -> float:
        return self.cfg.chirp_period_s

    @property
    def active_s(self) -> float:
        return self.cfg.n_loops * self.cfg.chirp_period_s

    @property
    def wavelength_m(self) -> float:
        return self.cfg.wavelength_m

    @property
    def v_max(self) -> float:
        return self.wavelength_m / (4 * self.loop_s)

    @property
    def dv(self) -> float:
        return self.wavelength_m / (2 * self.cfg.n_loops * self.loop_s)

    @property
    def frame_period_s(self) -> float:
        return self.frame_ms / 1000.0

    def describe(self) -> str:
        return (f"{self.name}: S {self.slope_mhz_us:g} MHz/us, idle {self.idle_us:g} us, dR {100 * self.range_res_m:.1f} cm, "
                f"R_max {self.max_range_m:.1f} m, v_max {self.v_max:.2f} m/s, dv {100 * self.dv:.1f} cm/s, "
                f"chirps {1e3 * self.active_s:.1f} ms")

    def sigmas(self, snr_lin, theta_rad, n_az: int = 12, d: float = 0.5):
        rho = np.maximum(np.asarray(snr_lin, float), 1.0)
        sb = np.sqrt((math.sqrt(HANN_NOISE_BW * 6.0) / (2 * math.pi)) ** 2 / rho + BIN_FLOOR ** 2)
        su = np.sqrt(6.0 / ((2 * math.pi * d) ** 2 * rho * (n_az ** 2 - 1)))
        su = np.sqrt(su ** 2 + (BIN_FLOOR / (n_az * d)) ** 2)
        st = su / np.maximum(np.cos(theta_rad), 0.2)
        return self.range_res_m * sb, st, self.dv * sb


def _base_lines() -> list[str]:
    return BASE_CFG.read_text(encoding="utf-8", errors="ignore").splitlines()


def _profile_line(base: str, profile_id: int, idle_us: float, slope: float) -> str:
    v = base.split()
    v[1] = str(profile_id)
    v[3] = f"{idle_us:g}"
    v[8] = f"{slope:g}"
    return " ".join(v)


def write_single_cfg(name: str, slope: float, idle_us: float, frame_ms: float) -> Path:
    out = [f"% generated by obstacle/methods/waveforms.py from base.cfg: chirp '{name}' alone (frame mode)",
           f"% slope {slope} MHz/us, idle {idle_us} us, frame {frame_ms} ms, numFrames 0 (continuous)"]
    for line in _base_lines():
        s = line.strip()
        if s.startswith("profileCfg"):
            line = _profile_line(s, 0, idle_us, slope)
        elif s.startswith("frameCfg"):
            v = s.split()
            v[4], v[6] = "0", f"{frame_ms:g}"
            line = " ".join(v)
        out.append(line)
    path = paths.WAVEFORMS / f"{name}.cfg"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    return path


MIN_GAP_MS = 5.0


def subframe_periods(active_ms: list[float], frame_ms: float) -> list[float]:
    slack = (frame_ms - sum(active_ms)) / len(active_ms)
    if slack < MIN_GAP_MS:
        need = sum(active_ms) + MIN_GAP_MS * len(active_ms)
        raise ValueError(f"the {len(active_ms)} sub-frames ({', '.join(f'{a:.1f}' for a in active_ms)} ms of chirps) need a "
                         f"frame of at least {need:.1f} ms ([radar] frame_ms = {frame_ms:g})")
    return [a + slack for a in active_ms]


def write_subframe_cfg(chirps: list[dict], periods_ms: list[float]) -> Path:
    base = _base_lines()
    prof = next(s.strip() for s in base if s.strip().startswith("profileCfg"))
    chirp_lines = [s.strip() for s in base if s.strip().startswith("chirpCfg")]
    frame = next(s.strip().split() for s in base if s.strip().startswith("frameCfg"))
    n_loops = int(frame[3])
    out = ["% generated by obstacle/methods/waveforms.py from base.cfg: ALL chirps preloaded as sub-frames",
           "% (advanced frame, dfeDataOutputMode 3): " + ", ".join(f"sub-frame {i} = '{c['name']}' (idle {c['idle_us']} us, "
                                                           f"{p:.2f} ms)" for i, (c, p) in enumerate(zip(chirps, periods_ms))),
           f"% frame {sum(periods_ms):g} ms; no reconfiguration while running"]
    for line in base:
        s = line.strip()
        if s.startswith("%") or not s:
            continue
        if s.startswith("dfeDataOutputMode"):
            out.append("dfeDataOutputMode 3")
        elif s.startswith("profileCfg"):
            out += [_profile_line(prof, i, c["idle_us"], c["slope_mhz_us"]) for i, c in enumerate(chirps)]
        elif s.startswith("chirpCfg"):
            if s == chirp_lines[0]:
                for i in range(len(chirps)):
                    for j, cl in enumerate(chirp_lines):
                        v = cl.split()
                        v[1], v[2], v[3] = str(4 * i + j), str(4 * i + j), str(i)
                        out.append(" ".join(v))
        elif s.startswith("frameCfg"):
            out.append(f"advFrameCfg {len(chirps)} 0 0 1 0 {len(chirps)}")
            out += [f"subFrameCfg {i} 0 {4 * i} {len(chirp_lines)} {n_loops} {p:.2f} 0 1 1 {p:.2f}"
                    for i, p in enumerate(periods_ms)]
            out += [f"subDataFrameCfg {i} {prof.split()[10]} {len(chirp_lines) * n_loops} 1"
                    for i in range(len(chirps))]
        else:
            out.append(s)
    path = paths.WAVEFORMS / "subframes.cfg"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    return path


class Library:

    def __init__(self, cfg: dict):
        chirps = cfg["waveform"]
        self.frame_ms = frame_ms_of(cfg)
        self.wf: dict[str, Waveform] = {}
        for i, c in enumerate(chirps):
            p = write_single_cfg(c["name"], c["slope_mhz_us"], c["idle_us"], self.frame_ms)
            self.wf[c["name"]] = Waveform(c["name"], float(c["slope_mhz_us"]), float(c["idle_us"]), self.frame_ms, i,
                                          with_layout(RadarConfig.from_cfg(p), paths.LAYOUT), p)
        periods = subframe_periods([1e3 * w.active_s for w in self.wf.values()], self.frame_ms)
        self.period_ms = dict(zip(self.wf, periods))
        self.start_ms = dict(zip(self.wf, np.r_[0.0, np.cumsum(periods)[:-1]].tolist()))
        self.subframe_path = write_subframe_cfg(chirps, periods)
        first = self.first
        for w in self.wf.values():
            if w.cfg.wire_bytes_per_frame(True) != first.cfg.wire_bytes_per_frame(True):
                raise ValueError(f"chirp {w.name} changes the frame size; only slope / idle time may differ")
            if abs(w.cfg.wavelength_m - first.cfg.wavelength_m) > 1e-9 or w.range_res_m != first.range_res_m:
                raise ValueError(f"chirp {w.name} changes the wavelength or range axis (calibration, reference)")
        self._looks = {}

    @property
    def first(self) -> Waveform:
        return next(iter(self.wf.values()))

    @property
    def names(self) -> list[str]:
        return list(self.wf)

    def __getitem__(self, name: str) -> Waveform:
        return self.wf[name]

    @property
    def min_period_ms(self) -> float:
        return min(self.period_ms.values())

    def look(self, name: str, revisit_s: float) -> Waveform:
        key = (name, round(revisit_s, 3))
        if key not in self._looks:
            self._looks[key] = replace(self.wf[name], frame_ms=1e3 * revisit_s)
        return self._looks[key]

    def describe(self) -> list[str]:
        return [w.describe() for w in self.wf.values()] + [
            f"advanced frame: {len(self.wf)} sub-frames ({', '.join(f'{p:.1f}' for p in self.period_ms.values())} ms) = "
            f"{self.frame_ms:g} ms; {len(self.wf) * self.first.cfg.wire_bytes_per_frame(True) / self.frame_ms / 1e3:.0f} MB/s "
            f"on the Ethernet link"]


def frame_ms_of(cfg: dict) -> float:
    rc = cfg["radar"]
    return float(rc["frame_ms"]) if "frame_ms" in rc else float(rc["subframe_ms"]) * len(cfg["waveform"])


def chirp_choice(cfg: dict, lib: Library, armed=None, policy: str | None = None):
    from methods.chirp_choice import ChirpChoice, SubFrame
    names = [n for n in lib.names if armed is None or n in armed] or [lib.first.name]
    sf = [SubFrame(n, lib[n], lib.start_ms[n] / 1e3, lib[n].active_s) for n in names]
    return ChirpChoice(sf, lib.frame_ms / 1e3, policy or cfg["radar"].get("look_policy", "cognitive"),
                       cfg["tracking"]["accel_sigma_mps2"], max(cfg["tracking"]["horizons_s"]))
