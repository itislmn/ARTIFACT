"""
radar_model.py - the chirps as the tracker sees them: the waveform library and the preloaded sub-frames
(advanced-frame cfg), each with its resolution, ambiguities and Cramer-Rao noise.

    from methods.radar_model import library_for
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field, replace
from pathlib import Path

import numpy as np

import paths  # noqa: F401  (import paths of ../estimation)
from estimation.core.radar import C0, RadarConfig, with_layout

BASE_CFG = paths.ESTIMATION / "config" / "awr2944_doa_perfect.cfg"
HANN_NOISE_BW = 1.5
BIN_FLOOR = 0.05


@dataclass(frozen=True)
class Waveform:
    name: str
    slope_mhz_us: float
    idle_us: float
    frame_ms: float
    cfg: RadarConfig = field(repr=False)
    path: Path = field(repr=False)
    subframe: int = -1
    start_ms: float = 0.0

    @property
    def range_res_m(self) -> float:
        return self.cfg.range_res_m

    @property
    def max_range_m(self) -> float:
        return 0.9 * self.cfg.fs_hz / 2 * C0 / (2 * self.cfg.slope_hz_per_s)

    @property
    def loop_s(self) -> float:
        return self.cfg.chirp_period_s

    @property
    def active_s(self) -> float:
        return self.cfg.n_loops * self.loop_s

    @property
    def slot_s(self) -> float:
        return self.cfg.idle_s + self.cfg.ramp_end_s

    @property
    def wavelength_m(self) -> float:
        return self.cfg.wavelength_m

    @property
    def v_max(self) -> float:
        return self.wavelength_m / (4 * self.loop_s)

    @property
    def dv(self) -> float:
        return self.wavelength_m / (2 * self.cfg.n_loops * self.loop_s)

    @property
    def frame_period_s(self) -> float:
        return self.frame_ms / 1000.0

    @property
    def mb_per_s(self) -> float:
        return self.cfg.wire_bytes_per_frame(True) / self.frame_period_s / 1e6

    def describe(self) -> str:
        return (f"{self.name}: S {self.slope_mhz_us:g} MHz/us, dR {100 * self.range_res_m:.1f} cm, "
                f"R_max {self.max_range_m:.1f} m, v_max {self.v_max:.2f} m/s, dv {100 * self.dv:.1f} cm/s, "
                f"{1000 / self.frame_ms:.0f} frames/s, {self.mb_per_s:.0f} MB/s")

    def sigmas(self, snr_lin, theta_rad, n_az: int = 12, d: float = 0.5):
        rho = np.maximum(np.asarray(snr_lin, float), 1.0)
        sb = np.sqrt((math.sqrt(HANN_NOISE_BW * 6.0) / (2 * math.pi)) ** 2 / rho + BIN_FLOOR ** 2)
        su = np.sqrt(6.0 / ((2 * math.pi * d) ** 2 * rho * (n_az ** 2 - 1)))
        su = np.sqrt(su ** 2 + (BIN_FLOOR / (n_az * d)) ** 2)
        st = su / np.maximum(np.cos(theta_rad), 0.2)
        return self.range_res_m * sb, st, self.dv * sb


def _base_lines() -> list[str]:
    return BASE_CFG.read_text(encoding="utf-8", errors="ignore").splitlines()


def write_waveform_cfg(name: str, slope_mhz_us: float, idle_us: float, frame_ms: float,
                       out_dir: Path = paths.WAVEFORM_DIR) -> Path:
    base = RadarConfig.from_cfg(BASE_CFG)
    t_mid = base.adc_start_s + 0.5 * base.n_samples / base.fs_hz
    f_centre = base.f0_hz + base.slope_hz_per_s * t_mid
    f0 = f_centre - slope_mhz_us * 1e12 * t_mid
    f_top = f0 + slope_mhz_us * 1e12 * base.ramp_end_s
    if f0 < 76e9 - 1 or f_top > 81e9 + 1:
        raise ValueError(f"waveform {name}: chirp {f0 / 1e9:.2f}-{f_top / 1e9:.2f} GHz leaves the 76-81 GHz band")
    out = [f"% generated by tracking/methods/radar_model.py from {BASE_CFG.name}: waveform '{name}'",
           f"% slope {slope_mhz_us} MHz/us, idle {idle_us} us, frame {frame_ms} ms, start {f0 / 1e9:.4f} GHz "
           f"(band centre {f_centre / 1e9:.3f} GHz kept), numFrames 0 (continuous)"]
    for line in _base_lines():
        s = line.strip()
        if s.startswith("profileCfg"):
            v = s.split()
            v[2] = f"{f0 / 1e9:.4f}".rstrip("0").rstrip(".")
            v[3] = f"{idle_us:g}"
            v[8] = f"{slope_mhz_us:g}"
            line = " ".join(v)
        elif s.startswith("frameCfg"):
            v = s.split()
            v[4] = "0"
            v[6] = f"{frame_ms:g}"
            line = " ".join(v)
        out.append(line)
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{name}.cfg"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    return path


MIN_GAP_MS = 5.0


def subframe_periods(active_ms: list[float], frame_ms: float) -> list[float]:
    slack = (frame_ms - sum(active_ms)) / len(active_ms)
    if slack < MIN_GAP_MS:
        need = sum(active_ms) + MIN_GAP_MS * len(active_ms)
        raise ValueError(f"the {len(active_ms)} sub-frames ({', '.join(f'{a:.1f}' for a in active_ms)} ms of chirps) need a "
                         f"frame of at least {need:.1f} ms ([radar] frame_ms = {frame_ms:g})")
    return [a + slack for a in active_ms]


def write_subframe_cfg(chirps: list[dict], periods_ms: list[float], out_dir: Path = paths.WAVEFORM_DIR) -> Path:
    base = _base_lines()
    chirp_lines = [s.strip() for s in base if s.strip().startswith("chirpCfg")]
    frame = next(s.strip().split() for s in base if s.strip().startswith("frameCfg"))
    n_loops = int(frame[3])
    profiles = []
    for i, c in enumerate(chirps):
        single = out_dir / f"{c['name']}.cfg"
        v = next(s.strip() for s in single.read_text(encoding="utf-8").splitlines() if s.startswith("profileCfg")).split()
        v[1] = str(i)
        profiles.append(" ".join(v))
    out = ["% generated by tracking/methods/radar_model.py: ALL chirps preloaded as sub-frames (advanced frame,",
           "% dfeDataOutputMode 3): " + ", ".join(f"sub-frame {i} = '{c['name']}' (idle {c['idle_us']} us, {p:.2f} ms)"
                                               for i, (c, p) in enumerate(zip(chirps, periods_ms))),
           f"% frame {sum(periods_ms):g} ms; armed once, never reconfigured"]
    for line in base:
        s = line.strip()
        if s.startswith("%") or not s:
            continue
        if s.startswith("dfeDataOutputMode"):
            out.append("dfeDataOutputMode 3")
        elif s.startswith("profileCfg"):
            out += profiles
        elif s.startswith("chirpCfg"):
            if s == chirp_lines[0]:
                for i in range(len(chirps)):
                    for j, cl in enumerate(chirp_lines):
                        v = cl.split()
                        v[1], v[2], v[3] = str(4 * i + j), str(4 * i + j), str(i)
                        out.append(" ".join(v))
        elif s.startswith("frameCfg"):
            out.append(f"advFrameCfg {len(chirps)} 0 0 1 0 {len(chirps)}")
            out += [f"subFrameCfg {i} 0 {4 * i} {len(chirp_lines)} {n_loops} {p:.2f} 0 1 1 {p:.2f}"
                    for i, p in enumerate(periods_ms)]
            out += [f"subDataFrameCfg {i} {profiles[i].split()[10]} {len(chirp_lines) * n_loops} 1"
                    for i in range(len(chirps))]
        else:
            out.append(s)
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "subframes.cfg"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    return path


def subframe_library(cfg: dict) -> dict[str, Waveform]:
    chirps = cfg["subframe"]
    frame_ms = frame_ms_of(cfg)
    out_dir = paths.WAVEFORM_DIR / "subframes"
    lib, active = {}, []
    for i, c in enumerate(chirps):
        p = write_waveform_cfg(c["name"], c["slope_mhz_us"], c["idle_us"], frame_ms, out_dir)
        rc = with_layout(RadarConfig.from_cfg(p), paths.LAYOUT)
        lib[c["name"]] = Waveform(c["name"], float(c["slope_mhz_us"]), float(c["idle_us"]), frame_ms, rc, p, i)
        active.append(1e3 * rc.n_loops * rc.chirp_period_s)
    periods = subframe_periods(active, frame_ms)
    write_subframe_cfg(chirps, periods, out_dir)
    starts = np.r_[0.0, np.cumsum(periods)[:-1]]
    lib = {n: replace(w, start_ms=float(st)) for (n, w), st in zip(lib.items(), starts)}
    first = next(iter(lib.values()))
    for wf in lib.values():
        if wf.cfg.wire_bytes_per_frame(True) != first.cfg.wire_bytes_per_frame(True):
            raise ValueError(f"sub-frame {wf.name} changes the frame size; only slope / idle time may differ")
    return lib


def frame_ms_of(cfg: dict) -> float:
    rc = cfg["radar"]
    return float(rc["frame_ms"]) if "frame_ms" in rc else float(rc["subframe_ms"]) * len(cfg["subframe"])


def library_for(cfg: dict) -> dict[str, Waveform]:
    if cfg.get("radar", {}).get("mode") == "subframes" and cfg.get("subframe"):
        return subframe_library(cfg)
    return waveform_library(cfg)


def waveform_library(cfg: dict) -> dict[str, Waveform]:
    lib = {}
    for w in cfg["waveform"]:
        p = write_waveform_cfg(w["name"], w["slope_mhz_us"], w["idle_us"], w["frame_ms"])
        rc = with_layout(RadarConfig.from_cfg(p), paths.LAYOUT)
        lib[w["name"]] = Waveform(w["name"], float(w["slope_mhz_us"]), float(w["idle_us"]), float(w["frame_ms"]), rc, p)
    first = next(iter(lib.values()))
    for wf in lib.values():
        if wf.cfg.wire_bytes_per_frame(True) != first.cfg.wire_bytes_per_frame(True):
            raise ValueError(f"waveform {wf.name} changes the frame size; only slope / idle / frame period may change")
    return lib
